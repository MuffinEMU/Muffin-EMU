"""Writes App/Localization/<code>.lproj/Localizable.strings from l10n/keys.json and
l10n/translations/<code>.json (English key -> translation).

A translation is only written when it keeps the key's format specifiers (%d, %@, %.1f ...) in the same
order; otherwise, or when one is missing, that string falls back to English (the key itself, which is
what lookup returns anyway) and the script says how many. en.lproj gets every key as itself, so English
is a listed localization. InfoPlist.strings carries the permission prompts.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'App', 'Localization')
# The specifiers the app's format strings use. Narrow on purpose: "70% of" is a percent sign, not "% o".
SPEC = re.compile(r'%(?:\d+\$)?(?:\.\d+)?(?:ll|l)?[@dfs]|%%')
INFOPLIST = ['NSMicrophoneUsageDescription', 'NSLocalNetworkUsageDescription']

def specs(s):
    return [m.group(0).split('$')[-1] for m in SPEC.finditer(s) if m.group(0) != '%%']

def escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t')

def write(path, pairs):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write('/* Generated by l10n/write_strings.py from l10n/translations. Edit the JSON, not this file. */\n\n')
        for k, v in pairs:
            f.write(f'"{escape(k)}" = "{escape(v)}";\n')

def main():
    keys = json.load(open(os.path.join(ROOT, 'l10n', 'keys.json'), encoding='utf-8'))
    infoplist = json.load(open(os.path.join(ROOT, 'l10n', 'infoplist.json'), encoding='utf-8'))
    write(os.path.join(OUT, 'en.lproj', 'Localizable.strings'), [(k, k) for k in keys])
    write(os.path.join(OUT, 'en.lproj', 'InfoPlist.strings'), [(k, infoplist[k]) for k in INFOPLIST])
    tdir = os.path.join(ROOT, 'l10n', 'translations')
    status = 0
    for name in sorted(os.listdir(tdir)):
        code = name[:-5]
        # <code>.json only: translators keep part files (<code>.part01.json) here while they work.
        if not name.endswith('.json') or '.' in code: continue
        t = json.load(open(os.path.join(tdir, name), encoding='utf-8'))
        pairs, missing, bad = [], 0, []
        for k in keys:
            v = t.get(k)
            if not isinstance(v, str) or not v.strip():
                missing += 1; continue
            if specs(v) != specs(k):
                bad.append(k); continue
            pairs.append((k, v))
        plist = [(k, t[f'InfoPlist:{k}']) for k in INFOPLIST if t.get(f'InfoPlist:{k}')]
        write(os.path.join(OUT, f'{code}.lproj', 'Localizable.strings'), pairs)
        write(os.path.join(OUT, f'{code}.lproj', 'InfoPlist.strings'), plist)
        print(f'{code}: {len(pairs)}/{len(keys)} translated, {missing} missing, {len(bad)} format mismatch')
        for k in bad[:5]: print(f'  mismatch: {k!r} -> {t[k]!r}')
        if missing + len(bad) > len(keys) * 0.02: status = 1
    sys.exit(status)

if __name__ == '__main__':
    main()
