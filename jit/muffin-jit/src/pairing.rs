// On-device pairing, for iOS 27 and later. The device can start a pairing to a host
// that advertises `_remotepairing-pairable-host._tcp`; here the host is MuffinEMU
// itself, running on the same device. We advertise the service, accept the
// device-initiated pairing, show the device a setup code, and keep the resulting
// pairing file. After this, `muffin_jit_connect` has what it needs and no computer
// was ever involved.
//
// The PIN is generated by the pairing protocol and shown to the user to type into
// the system prompt; it is never logged. The pairing file is handed back as bytes
// the caller stores securely and frees with `muffin_jit_bytes_free`.

use std::ffi::{c_char, c_void, CString};
use std::net::Ipv4Addr;
use std::time::Duration;

use idevice::remote_pairing::{
    PairableHost, PairableHostInfo, RpPairingFile, RpPairingSocket, PAIRABLE_HOST_SERVICE_TYPE,
};
use mdns_sd::{ServiceDaemon, ServiceInfo};
use tokio::net::TcpListener;

use crate::ffi::{cstr, report, MjProgress};
use crate::{err_out, set_err, MjStatus};

/// Advertises MuffinEMU as a pairable host and accepts one device-initiated
/// pairing. On success the pairing file bytes are written to `out_pairing` /
/// `out_pairing_len` (free with `muffin_jit_bytes_free`). The PIN callback is
/// invoked with the setup code to show the user.
#[no_mangle]
pub unsafe extern "C" fn muffin_jit_pair_on_device(
    name: *const c_char,
    model: *const c_char,
    timeout_ms: u32,
    pin_cb: Option<extern "C" fn(ctx: *mut c_void, pin: *const c_char)>,
    pin_ctx: *mut c_void,
    cb: MjProgress,
    ctx: *mut c_void,
    out_pairing: *mut *mut u8,
    out_pairing_len: *mut usize,
    out_err: *mut *mut c_char,
) -> i32 {
    if out_pairing.is_null() || out_pairing_len.is_null() {
        set_err(out_err, "output pointers were null");
        return MjStatus::InvalidArg as i32;
    }
    *out_pairing = std::ptr::null_mut();
    *out_pairing_len = 0;

    let args = (|| {
        Ok::<_, String>((
            cstr(name, "name")?.to_string(),
            cstr(model, "model")?.to_string(),
        ))
    })();
    let (name, model) = match args {
        Ok(v) => v,
        Err(e) => {
            set_err(out_err, e);
            return MjStatus::InvalidArg as i32;
        }
    };

    // The raw PIN context pointer has to cross the async boundary.
    struct PinCtx(*mut c_void);
    unsafe impl Send for PinCtx {}
    let pin_holder = PinCtx(pin_ctx);

    report(cb, ctx, 30, "Getting ready to pair");
    let res = crate::run_blocking(async move {
        // Bind first so the advertisement carries the real port.
        let listener = TcpListener::bind((Ipv4Addr::UNSPECIFIED, 0))
            .await
            .map_err(|e| format!("could not open a pairing port: {e}"))?;
        let port = listener
            .local_addr()
            .map_err(|e| format!("could not read the pairing port: {e}"))?
            .port();

        let mut pairing_file = RpPairingFile::generate(&name);
        let mut host_info = PairableHostInfo::generate(&name, &model);
        host_info.allows_pinless_pairing = false;
        let service_identifier = pairing_file.identifier.clone();

        let mdns = ServiceDaemon::new().map_err(|e| format!("could not start Bonjour: {e}"))?;
        mdns.set_service_name_len_max(30).ok();
        let hostname = format!("muffinemu-{}.local.", &service_identifier[..8.min(service_identifier.len())]);
        let txt = host_info.mdns_txt_records(&service_identifier);
        let properties: Vec<(&str, &str)> =
            txt.iter().map(|(k, v)| (k.as_str(), v.as_str())).collect();
        let service_info = ServiceInfo::new(
            PAIRABLE_HOST_SERVICE_TYPE,
            &service_identifier,
            &hostname,
            "",
            port,
            &properties[..],
        )
        .map_err(|e| format!("could not build the pairing advertisement: {e}"))?
        .enable_addr_auto();
        mdns.register(service_info)
            .map_err(|e| format!("could not advertise for pairing: {e}"))?;

        report(cb, ctx, 31, "Waiting for the device");
        let accept = listener.accept();
        let (stream, _peer) = match tokio::time::timeout(Duration::from_millis(timeout_ms as u64), accept).await {
            Ok(Ok(s)) => s,
            Ok(Err(e)) => return Err(format!("the device could not connect: {e}")),
            Err(_) => return Err("timed out waiting for the device to start pairing".to_string()),
        };

        report(cb, ctx, 32, "Pairing");
        let socket = RpPairingSocket::new_device(stream);
        let mut host = PairableHost::new(socket, host_info);
        let pin_holder = pin_holder;
        host.accept(&mut pairing_file, |pin: String| async move {
            if let Some(cb) = pin_cb {
                if let Ok(c) = CString::new(pin) {
                    cb(pin_holder.0, c.as_ptr());
                }
            }
        })
        .await
        .map_err(|e| format!("pairing did not complete: {e}"))?;

        let _ = mdns.shutdown();
        let bytes = pairing_file.to_bytes();
        Ok::<Vec<u8>, String>(bytes)
    });

    let (code, val) = err_out(res, out_err, MjStatus::PairingInvalid);
    if let Some(mut bytes) = val {
        bytes.shrink_to_fit();
        let len = bytes.len();
        let ptr = bytes.as_mut_ptr();
        std::mem::forget(bytes);
        *out_pairing = ptr;
        *out_pairing_len = len;
        report(cb, ctx, 33, "Paired");
    }
    code
}

/// Frees a byte buffer handed back by `muffin_jit_pair_on_device`.
#[no_mangle]
pub unsafe extern "C" fn muffin_jit_bytes_free(ptr: *mut u8, len: usize) {
    if !ptr.is_null() && len > 0 {
        drop(Vec::from_raw_parts(ptr, len, len));
    }
}
